#!/usr/bin/env bash
# Generates the notes pages that come from other files: Recently changed, and in the Claude section the handoff and report lists, the roadmap copies and Open questions.
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: gen-pages.sh NOTES_DIR
Writes docs/recent.md and, under docs/claude/: batches/index.md, reports/index.md, roadmaps/*.md, open-questions.md, due-dates.md.
A page is replaced only when its content changes. Run by build.sh before the MkDocs build.
ROADMAP_REPOS: space-separated name=path list; each repo's docs/roadmap.md or docs/working/roadmap.md is copied.
DUE_DATES_JSON: the Due-Dates list (default /var/lib/due-dates/due-dates.json), rendered by Docker/Due-Dates/due_dates.py md.
EOF
}
case "${1:-}" in -h|--help|'') usage; [ -n "${1:-}" ]; exit ;; esac

notes=$1; docs="$notes/docs"; c="$docs/claude"
ROADMAP_REPOS=${ROADMAP_REPOS:-"claude-config=$HOME/development/private/claude-config fastpi=$HOME/Projects landingpage=$HOME/landingpage tower=$HOME/HomeLab-Unraid-Tower"}
DUE_DATES_JSON=${DUE_DATES_JSON:-/var/lib/due-dates/due-dates.json}
DUE_DATES_PY="$(cd "$(dirname "$0")/../Due-Dates" && pwd)/due_dates.py"
replace_if_changed() { if cmp -s "$1" "$2"; then rm -f "$1"; else mv "$1" "$2"; fi; }
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
mkdir -p "$c/batches" "$c/reports" "$c/roadmaps"
title() { sed -n 's/^# //p' "$1" | head -1; }

# Recently changed: one row per page from git history (first commit = added, last commit = updated), newest first.
{ printf '# Recently changed\n\nNewest first, from the notes history. New pages are marked 🆕.\n\n| Date | Page | |\n|---|---|---|\n'
  (cd "$docs" && find . -name '*.md' -not -path './working/*' -not -path './claude/reports/archive/*' -not -path './claude/roadmaps/*' | sed 's#^\./##') | while read -r p; do
    case $p in index.md|recent.md|chapter-*|*/index.md|claude/open-questions.md) continue;; esac
    last=$(git -C "$notes" log -1 --format=%cs -- "docs/$p" 2>/dev/null || true); first=$(git -C "$notes" log --diff-filter=A --format=%cs -- "docs/$p" 2>/dev/null | tail -1 || true)
    [ -n "$last" ] || continue; t=$(title "$docs/$p")
    printf '%s|| %s | [%s](%s) | %s |\n' "$last" "$last" "${t:-$p}" "$p" "$([ "$first" = "$last" ] && echo 🆕 new || echo updated)"
  done | sort -r | head -20 | cut -d'|' -f3- | sed 's/^/|/'; } > "$tmp/recent.md"
replace_if_changed "$tmp/recent.md" "$docs/recent.md"

# Batch handoffs: one row per batches/<date>.md, newest first.
{ printf '# Batch handoffs\n\nOne file per batch: scope, rules in effect, status log, how to resume. Newest first; this list is generated by the build. Handoffs before 2026-11-19 are in Claude'"'"'s memory archive.\n\n| Date | Handoff |\n|---|---|\n'
  for f in $(ls -r "$c"/batches/20*.md 2>/dev/null); do b=$(basename "$f" .md)
    printf '| %s | [%s](%s.md) |\n' "$b" "$(title "$f")" "$b"
  done; } > "$tmp/batches.md"
replace_if_changed "$tmp/batches.md" "$c/batches/index.md"

# Batch reports: one file per date, newest first, with each run's bold summary line.
{ printf '# Batch reports\n\nOne file per date, kept forever; a day with several runs has one section per run. Newest first; this list is generated by the build. Older material of a date is linked from its page.\n\n| Date | Report | Summary |\n|---|---|---|\n'
  for f in $(ls -r "$c"/reports/20*.md 2>/dev/null); do b=$(basename "$f" .md)
    s=$({ grep -E '^\*\*.+\*\*' "$f" || true; } | sed -E 's/^\*\*([^*]+)\*\*.*/\1/' | paste -sd'/' - | sed 's#/# · next run: #g; s/|/\\|/g')
    printf '| %s | [%s](%s.md) | %s |\n' "$b" "$(title "$f" | sed 's/|/\\|/g')" "$b" "$s"
  done; } > "$tmp/reports.md"
replace_if_changed "$tmp/reports.md" "$c/reports/index.md"

# Roadmaps: a copy of each repo's roadmap; links that point into the repo become plain text.
found=()
for entry in $ROADMAP_REPOS; do name=${entry%%=*}; repo=${entry#*=}
  src=""; for r in "$repo/docs/roadmap.md" "$repo/docs/working/roadmap.md"; do [ -f "$r" ] && { src=$r; break; }; done
  [ -n "$src" ] || continue; found+=("$name")
  { sed -n '1{/^# /p}' "$src"
    printf '\n!!! note "Copy of `%s`"\n    Refreshed on every notes build. Edit the source, not this page.\n\n' "$src"
    sed '1{/^# /d}' "$src" | perl -pe 's/(!?)\[([^\]]*)\]\((?!https?:|mailto:|#)[^)]*\)/$2/g'; } > "$tmp/rm-$name.md"
  replace_if_changed "$tmp/rm-$name.md" "$c/roadmaps/$name.md"
done
for f in "$c"/roadmaps/*.md; do n=$(basename "$f" .md)
  [ "$n" = index ] || printf '%s\n' "${found[@]}" | grep -qx "$n" || rm -f "$f"
done
{ printf '# Roadmaps\n\nOne copy per repo, refreshed on every build; the repo file stays the source.\n\n| Repo | Roadmap |\n|---|---|\n'
  for n in "${found[@]}"; do printf '| %s | [%s](%s.md) |\n' "$n" "$(title "$c/roadmaps/$n.md")" "$n"; done; } > "$tmp/roadmaps.md"
replace_if_changed "$tmp/roadmaps.md" "$c/roadmaps/index.md"

# Open questions: roadmaps' "Open questions", the latest report's "❓" sections, the reminders' open table.
section_items() { awk -v re="$2" '/^#+ /{on = ($0 ~ re); next} on && /^- /' "$1"; }
latest=$(ls -r "$c"/reports/20*.md 2>/dev/null | head -1 || true)
{ printf '# Open questions\n\nEverything that waits on an answer, collected on every build. Answer at the source; each block links to it.\n'
  for n in "${found[@]}"; do q=$(section_items "$c/roadmaps/$n.md" '^#+ Open questions')
    [ -n "$q" ] && printf '\n## Roadmap: %s\n\nSource: [roadmap](roadmaps/%s.md)\n\n%s\n' "$n" "$n" "$q"
  done
  if [ -n "$latest" ]; then b=$(basename "$latest" .md); q=$(section_items "$latest" '^#+ ❓')
    [ -n "$q" ] && printf '\n## Latest batch report\n\nSource: [%s](reports/%s.md)\n\n%s\n' "$b" "$b" "$q"
  fi
  if [ -f "$c/reminders.md" ]; then
    q=$(awk -F'|' '/^\| *Due *\|/{on=1; next} on && /^\|---/{next} on && /^\|/{gsub(/^ +| +$/, "", $2); gsub(/^ +| +$/, "", $3); gsub(/^ +| +$/, "", $4); printf "- **%s** %s: %s\n", $2, $3, $4; next} on{exit}' "$c/reminders.md")
    [ -n "$q" ] && printf '\n## Reminders\n\nSource: [open decisions and reminders](reminders.md)\n\n%s\n' "$q"
  fi; } > "$tmp/open.md"
replace_if_changed "$tmp/open.md" "$c/open-questions.md"

# Due dates: the Due-Dates list as a table (dates are entered once, in Docker/Due-Dates/due-dates.toml).
if ! python3 -I "$DUE_DATES_PY" md "$DUE_DATES_JSON" > "$tmp/due.md" 2>/dev/null; then
  printf '# Due dates\n\nThe list is not generated yet (`due-dates.timer` on fastpi, source `Docker/Due-Dates/due-dates.toml`).\n' > "$tmp/due.md"
fi
replace_if_changed "$tmp/due.md" "$c/due-dates.md"
